            <q-item-section>
              <b
                >What is the difference between a dam owner and a dam
                regulator?</b
              >
              <br />
              A dam owner is liable for the dam and is responsible for its
              upkeep, upgrade and repair. A dam regulator is responsible for
              enforcing policies, inspecting the safety of a dam, review of
              plans for new construction or rehabilitation and has a broader
              overall outlook on the construction and upkeep of dams. Owners can
              be private citizens or companies, quasi-governmental bodies, state
              or local governments or federal agencies. Regulators work for the
              state or federal government. Most dams – about 70% in the US – are
              regulated by state agencies. All states have regulatory programs
              in place except one, Alabama. Federal agencies regulated about 14%
              of dams in the U.S. The remaining percentage are unregulated due
              to state or federal exemptions. (ASDSO)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>Who owns the dams that are being removed?</b>
              <br />
              Private businesses, federal agencies, state agencies, local
              governments, or public utilities may own dams. Most of the dams
              removed to date have been owned privately, by local government, or
              by public utilities. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>Who will own the exposed land?</b>
              <br />
              Land ownership questions can typically be answered by referring to
              the deeds for the specific dam property and the adjacent
              properties. The dam’s deed might include all of the land that was
              flowed and the exposed land would revert to the dam owner. Some
              dam owners have donated these lands to land trusts or quit-claim
              deeded them to the adjacent land owners or municipalities. In
              other cases, the land currently underwater may be publicly owned,
              or it may simply revert to the property owners bordering the
              restored river. Deeds can be researched at that county’s Registry
              of Deeds. (NHDES)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>How will property values be affected?</b>
              <br />
              This is a difficult question to answer because it is very much
              dependent on the particular site and is strongly influenced by
              other issues, for example, the real estate market, location in
              state, characteristics of the property. Studies have not shown
              strong correlations between dam removal and changes in property
              values. For instance, if a dam removal restores sport fishing,
              property values may increase. If, on the other hand, a dam is
              removed that creates a pond unique to the area, property values
              may decline. As shown at sites across the country, the removal of
              a particular dam will be seen as a good thing to some potential
              buyers and a bad thing to others. One person’s lost pond is
              another person’s restored river. (NHDES)
            </q-item-section>
