    <q-expansion-item switch-toggle-side label="Restoration"
      ><div class="q-ma-md">
        <q-list bordered separator>
          <q-item>
            <q-item-section>
              <b>Can rivers be restored through dam removal?</b>
              <br />
              Although most rivers cannot be completely restored to historic
              conditions – simply because of the amount of development that has
              occurred on and along them – dam removal can often recreate
              conditions that move the river towards those historic conditions.
              For example, migratory fish are returning to the Musconetcong,
              Millstone, and Paulins Kill after dam removals on those rivers.
              <br /><br />
              Nationally, fish are returning to historic stretches of river that
              had been previously obstructed on Butte Creek in California, the
              Souadabscook River in Maine, and the Clearwater River in Idaho, as
              a result of dam removals. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b
                >Will the removal of a dam matter if other dams in the system
                are not removed?</b
              >
              <br />
              Some rivers are so heavily developed and dammed that removal of
              one dam on that river will only return flows to a small portion of
              the river. Generally, dams that have been targeted for removal are
              strategically located – removal will open up a section of the
              river critical to fish and wildlife and/or recreation. In some
              cases, this additional section of river is enough to sustain
              crucial populations of endangered or threatened species of fish,
              mollusks, and other wildlife. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>How does dam removal affect fish?</b>
              <br />
              Dam removal benefits fish in many ways, including: (1) removing
              obstructions to upstream and downstream migration; (2) restoring
              natural riverine habitat; (3) restoring natural seasonal flow
              variations; (4) eliminating siltation of spawning and feeding
              habitat above the dam; (5) allowing debris, small rocks and
              nutrients to pass below the dam, creating healthy habitat; (6)
              eliminating unnatural temperature variations below the dam; and
              (7) removing turbines that kill fish. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b
                >How will the dam’s removal affect fish and wildlife habitats in
                the area?</b
              >
              <br />
              Dams alter the natural physical, biological and chemical functions
              of rivers. And, since healthy rivers are considered the lifeblood
              of healthy habitats, dams can result in unsustainable and degraded
              conditions for a variety of aquatic and terrestrial species. The
              habitats that have been created solely because of the dam’s
              presence will change if the dam is removed. For instance, a deep
              water marsh may be restored to a shallow marsh or a wet meadow. NJ
              Fish and Wildlife and other natural resources agencies can help
              provide site-specific information and predicted changes. (NHDES)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b
                >How will fishing opportunities change if the dam is removed?</b
              >
              <br />
              Dam removal improves the health of the river and aquatic habitat,
              typically to such an extent that anglers can look forward to
              increased numbers of fish and more places to fish for them. In
              some cases, removing a dam will change the type of fishery. For
              instance, a warm water fishery may be restored to a cool or
              coldwater fishery. In many cases, free-flowing rivers allow a
              wider variety of warm, cool and coldwater species to seasonally
              occupy portions of the same river, providing greater fishing
              variety. Anglers often like to fish right below dams, and some may
              oppose removal because they feel they’ll lose a good fishing spot.
              But it’s important to realize that the fish aren’t necessarily
              there because it’s good habitat, they’re often there because
              they’re prevented from moving further upstream. (NHDES)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>What will the restored river look like?</b>
              <br />
              Generally, the easiest way to predict how a river would look if a
              dam were removed is to look at the river upstream of the
              impoundment and downstream of the dam. Unless there is a
              significant geologic feature (e.g., a waterfall) in the impounded
              stretch of the river, it is unlikely that the restored river will
              be significantly different than what is seen in free-flowing parts
              of the river. Bear in mind that some dams are built to
              artificially raise the water level of a natural lake or pond. If
              that is the case, the extent of the pond post-dam removal can be
              predicted through modeling and/or sounding surveys. (NHDES)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>What will the newly exposed pond bottom look like?</b>
              <br />
              Land will be exposed when an impoundment is drawn down during dam
              removal. The amount of land that will be exposed depends upon the
              site conditions. If nearby sections of the free-flowing river have
              rocky banks, chances are that the restored section will too. If
              nearby sections of the river are vegetated, chances are that newly
              exposed lands will re-vegetate within a matter of weeks during
              growing seasons, thanks to the many seeds that have accumulated in
              the sediment over the years. Depending on the time of year and
              make-up of the sediment that is exposed, there may be an odor of
              decomposition for a short period of time (typically ranging from a
              few days to a few weeks). However, once this “new” land is exposed
              to sunlight and oxygen, plants grow very quickly, drying up the
              water-logged sediment in the process. Of course, if the exposed
              land is subject to tidal action or other significant water level
              fluctuations, this area may not revegetate as much or as quickly.
              (NHDES)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>How quickly do rivers recover after dam removal?</b>
              <br />
              Rivers are very dynamic and resilient systems. Experience has
              shown that natural river systems can be restored relatively
              rapidly after dam removal. For example, spawning fish returned to
              the Musconetcong, Millstone, and Paulins Kill Rivers only months
              after dam removal projects there. (AR)
            </q-item-section>
          </q-item>
