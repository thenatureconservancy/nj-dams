            <q-item-section>
              <b>Why are some dams being removed?</b>
              <br />
              There has been a growing movement to remove dams where the costs –
              including environmental, safety, and socio-cultural impacts –
              outweigh the benefits – including hydropower, flood control,
              irrigation, or recreation – or where the dam no longer serves any
              useful purpose. The goal of removal can be multi-faceted,
              including restoring flows for fish and wildlife, reinstating the
              natural sediment and nutrient flow, eliminating safety risks,
              restoring opportunities for recreation, and saving taxpayer money.
              (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>How are dams removed?</b>
              <br />
              Because dams and rivers vary greatly, physical removal strategies
              and techniques may also vary on a case by case basis. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>How many dams have been removed to date?</b>
              <br />
              According to American Rivers, 1,578 dams have been removed over
              the past 100 years in this country. AR is still in the process of
              gathering this data, so that figure continues to increase as more
              information becomes available. You can view an interactive map of
              all known U.S. dam removals. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>Who decides that dams should be removed?</b>
              <br />
              The decision to remove a dam is made by varying entities,
              depending on the regulatory oversight of the dam. In most cases,
              the dam owner itself is the decision-maker, often deciding that
              the costs of continuing to operate and maintain the dam are more
              than removing the dam. State dam safety offices can often order a
              dam to be removed if there are major safety concerns. State fish
              and wildlife offices are also often involved in the
              decision-making, particularly when the goals of the project
              include restoration of habitat for migratory and resident aquatic
              species. If the dam in question is a hydropower facility, the
              Federal Energy Regulatory Commission can order a hydropower dam
              under their jurisdiction to be removed for both environmental and
              safety reasons. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b
                >How can the benefits of a dam be replaced when it is
                removed?</b
              >
              <br />
              While dams serve a number of human needs, society has developed
              ways to address many of these needs without dams. For instance,
              flood control can often be accomplished more effectively and for
              less money by restoring wetlands, maintaining riparian buffers, or
              moving people out of the floodplain. Updating antiquated
              irrigation systems and replacing inappropriate crops can
              dramatically reduce the need for dams and reservoirs in the arid
              West. Rather than plugging rivers with multiple hydropower dams, a
              cheaper and less environmentally harmful solution is to use
              existing energy efficiency technologies. For example, the three
              megawatts of power lost in the removal of the Edwards Dam, on the
              Kennebec River in Maine, can be replaced simply by replacing
              75,000 light bulbs with energy efficient bulbs. Many dams that
              have been removed no longer had any beneficial use or that use was
              very limited. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>What are the potential downsides to dam removal?</b>
              <br />
              Dam removal does result in fundamental changes to the local
              environment. The reservoir will be eliminated, and with it the
              flat-water habitat that had been created. Wetlands surrounding the
              reservoir may also be drained, although new wetlands are often
              created both in the newly restored river reach above the former
              dam site and in the river below. Sediment that collects behind a
              dam, sometimes over hundreds of years, may contain toxics such as
              pcbs, dioxide, and heavy metals. Removal of these toxic materials
              is often extremely expensive, and the threat of re-suspending
              these toxic-laden sediments in the process of dam removal has the
              potential to damage downstream water quality and threaten the
              health of fish and wildlife and water users. These impacts,
              however, can be prevented through proper removal techniques. (AR)
              <br /><br />
              Short term impacts of the dam removal itself can include increased
              water turbidity and sediment buildup downstream from releasing
              large amounts of sediment from the reservoir, and water quality
              impacts from sudden releases of water and changes in temperature.
              It has been demonstrated that these short-term impacts are greatly
              outweighed by the quick recovery of the system and the long-term
              benefits that result. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>Will there be an increase in flooding?</b>
              <br />
              This would only be a concern if the dam actually provides flood
              control, however, this is true for only a very small percentage of
              dams. Flood control dams are fairly easy to recognize because they
              tend to have fluctuating water levels, and relatively low water
              levels except during flood events. It is important to note that
              dams can actually increase the risk of flooding both downstream
              and upstream of the dam, due to dam disrepair and/or misoperation.
              (NHDES)
              <br /><br />
              In heavy rainfall or flooding, some dams are designed to hold back
              some of the water flowing downstream, protecting people and
              property downstream from higher water. This naturally results in
              higher water upstream of the dam, but auxiliary spillways are
              designed to pass excess flood waters downstream. However, most
              dams in the state are not designed to function as flood control
              structures. They are “run of the river” dams designed to hold
              relatively stable water levels in the impoundment. Flood
              situations can sometimes exceed the capabilities of either type
              dam, resulting in a failure and a more drastic and sudden flooding
              of downstream property. Constant maintenance of dams, and
              awareness of dam operators is essential to protecting the public
              in flood situations. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>Does the dam have historical value?</b>
              <br />
              Part of the dam removal planning process is to assess the
              project’s potential to impact historical resources. In accordance
              with the National Historic Preservation Act, the State Historic
              Preservation Office must be consulted about the project as early
              as possible in the project planning process. They may recommend
              further study to determine the historic value of the site, based
              on both archaeological and architectural criteria. At some project
              sites the dam’s historic contributions are honored with
              interpretive signs, recovered mill stones and other information.
              In other cases, when a dam is historically significant, dam
              removal may not be appropriate and other alternatives may need to
              be considered. (NHDES)
            </q-item-section>
          </q-item>
