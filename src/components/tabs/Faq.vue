            <q-item-section>
              <b>How many dams are there in the United States?</b>
              <br />
              The exact number of dams is not known. There are more than 90,000
              (as per more current info below) dams in the US Army Corps of
              Engineers’ (Corps) National Inventory of Dams (NID), which is the
              most comprehensive inventory of dams nationwide. However, this
              inventory only covers dams that meet minimum height and
              impoundment requirements, so an unknown number of small dams are
              not included in the inventory. Of the 90,000 dams in the database,
              approximately 66,000 are located on rivers (the remainder impound
              water off-river). (AR)
            </q-item-section>
          </q-item>
