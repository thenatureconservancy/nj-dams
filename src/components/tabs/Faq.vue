          <q-item>
            <q-item-section>
              <b>What do the different classifications of dams mean?</b>
              <br />
              There are four hazard classifications of dams in New Jersey. The
              classifications relate to the potential for property damage and/or
              loss of life should the dam fail:<br />
              <ul>
                <li>
                  Class I (High-Hazard Potential) – Failure of the dam may
                  result in probable loss of life and/or extensive property
                  damage.
                </li>
                <li>
                  Class II (Significant-Hazard Potential) – Failure of the dam
                  may result in significant property damage; however loss of
                  life is not envisioned.
                </li>
                <li>
                  Class III (Low-Hazard Potential) – Failure of the dam is not
                  expected to result in loss of life and/or significant property
                  damage.
                </li>
                <li>
                  Class IV (Small-Dam Low-Hazard Potential) – Failure of the dam
                  is not expected to result in loss of life or significant
                  property damage. Dam must also meet the requirements of a
                  Class IV dam below. (NJDS)
                </li>
              </ul>
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>What qualifies as a Class IV dam?</b>
              <br />
              A Class IV Dam must meet the following:<br />
              <ul>
                <li>Drainage area must be less than 150 acres.</li>
                <li>Dam Height must be less than 15 feet.</li>
                <li>
                  Dam must not have the potential to impound more than 15
                  acre-feet of water.
                </li>
                <li>Dam must pose Low Hazard potential.</li>
                <li>
                  Spillway capacity must safely pass the 24-hour 100-year
                  frequency Type III storm plus 50 percent.
                </li>
              </ul>
              The complete definition of a Class IV dam is listed in the New
              Jersey Dam Safety Standards (N.J.A.C. 7:20-1.8 a-4). You may also
              see the graphical demonstration of the definition of a dam. (NJDS)
