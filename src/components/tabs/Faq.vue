            <q-item-section>
              <b>What is the Infrastructure Report Card?</b>
              <br />
              The American Society of Civil Engineers (ASCE) released a Report
              Card for America’s Infrastructure every 4 years. The report card
              grades each facet of America’s Infrastructure in order to
              understand the funding required to address each issue, as well as
              to understand the overall condition and maintenance each facet
              already receives. As part of the report, ASCE considers the
              condition of dams and the state of regulatory and owner oversight.
              <br /><br />
              ASCE considers America’s dams to be in poor to fair condition and
              that dam rehabilitation and safety should be of significant
              concern.
              <br />
              <br />
              The 2017 report card gave Infrastructure as a whole received a D+
              while the conditions of dams received a D. Dams also received a D
              in 2013, the last time ASCE released a report.
              <br />
              <br />

              To read the report on dams visit
