              <b>Who regulates dam operations?</b>
              <br />
              A number of state and federal agencies are responsible for
              regulating dams. In New Jersey, the Department of Environmental
              Protection, Bureau of Dam Safety regulates most dams. Dams owned
              by federal agencies are self-regulated. Non-federal dams that
              produce hydropower are regulated by the Federal Energy Regulatory
              Commission (FERC). (AR)
