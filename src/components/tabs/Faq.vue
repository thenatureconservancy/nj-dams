            <q-item-section>
              <b
                >Do all dams pose a danger to those who swim, fish or boat near
                them?</b
              >
              <br />
              While all dams are potentially dangerous, low-head dams are
              especially dangerous because the water around them often appears
              to be tranquil and inviting. Many drowning victims deliberately
              jump from or float over them without knowing the risks. Others are
              caught unaware, as low head dams are notoriously difficult to spot
              from upstream. The victims of these dams include many would-be
              rescuers and first responders who lost their lives trying to save
              others caught in the hydraulic current. About 91% of drownings and
              other dam-related deaths occur in the period from April to August.
              Many people take advantage of the relatively high waters upstream
              from a dam to cool off or spend some time having fun with friends
              and family. Others take advantage of natural habitats near dams to
              fish.
              <br /><br />
              Swimming, boating, and fishing account for the overwhelming
              majority of incidents at dams in the United States. According to
              information collected by Tony Bennett on behalf of the Canadian
              Dam Association and the International Commission on Large Dams,
              these activities and related activities account for over 75% of
              incidents at dams, with fishing alone accounting for over a
              quarter. (AR)
