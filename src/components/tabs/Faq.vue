            <q-item-section>
              <b>Who pays for dam removal?</b>
              <br />
              Who pays for the removal of a dam is often a complex issue. In
              past cases, removal has been financed by the dam owner, local,
              state and federal governments, and in some cases agreements
              whereby multiple stakeholders contribute to cover the costs. (AR)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>Is it cost effective to remove a dam? </b>
              <br />
              Dam removal can be expensive in the short term, but in most cases
              where dams have been removed or are being considered for removal,
              money is actually saved over the long term. Removal eliminates the
              expenses associated with maintenance and safety repairs, as well
              as direct and indirect expenses associated with fish and wildlife
              protection (e.g. fish ladders and mitigation for fish mortality).
              In addition, removal often generates income from newly available
              recreation opportunities – including fishing, kayaking, and
              rafting – which may actually result in a net economic benefit. In
              some areas, dam removal may allow resumption of commercial fishing
              activities. (AR)
