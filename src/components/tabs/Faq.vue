            <q-item-section>
              <b>What is a dam?</b>
              <br />
              There are a number of technical and legal definitions of a dam but
              generally it is any structure that impounds or diverts water. In
              New Jersey, a dam is any artificial dike, levee or other barrier,
              together with appurtenant works, which is constructed for the
              purpose of impounding water on a permanent or temporary basis,
              that raises the water level five feet or more above the usual,
              mean, low water height when measured from the downstream
              toe-of-dam to the emergency spillway crest or, in the absence of
              an emergency spillway, the top-of-dam. (NJDS)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>How do I measure dam height?</b>
              <br />
              Height of dam is the vertical dimension when measured from either
              the invert of the outlet pipe or, in the absence of an outlet
              pipe, the lowest point in the stream bed or ground surface at the
              downstream toe of dam, whichever is lower, to the top-of-dam. See
              the graphical demonstration of the definition of a dam. (NJDS)
            </q-item-section>
          </q-item>
          <q-item>
            <q-item-section>
              <b>What benefits do dams provide?</b>
              <br />
              Dams may provide a variety of benefits, including water supply,
              power generation, flood control, recreation, and irrigation. (AR)
            </q-item-section>
          </q-item>
