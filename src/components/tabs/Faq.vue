            <q-item-section>
              <b>What is the National Inventory of Dams (NID)?</b>
              <br />
              The U.S. Army Corps of Engineers maintains the National Inventory
              of Dams (NID) to help compile national data on dams in the United
              States. The NID lists over 90,000 dams. State and Federal
              regulatory agencies submit data to the NID. <br /><br />

              The NID gives national and state by state information on the
              current state of dams. To be a part of the NID, the dam must
              either be: of high- or significant-hazard potential
              classification, equal or exceed 25 feet in height and exceed 15
              acre-feet in storage or equal or exceed 50 acre-feet storage and
              exceed 6 feet in height. To access the site visit:
              nid.usace.army.mil/ (ASDRSO)
            </q-item-section>
          </q-item>
