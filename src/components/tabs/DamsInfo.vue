  <div id="purpose" class="q-my-md">
    <div class="text-bold">Purpose of Dams</div>
    <div>
      Dams have existed since the dawn of the human race. Creating water storage
      for livestock and irrigation was the first reason to impound water. Over
      the past few centuries, dams became integral to humanity’s need for
      mechanical power. Water wheels were erected to run in confined raceways;
      their rotational power converted to mechanical energy that ground grain
      into flour and ran the early machines of commerce.
      <br /><br />
      The citizens of many early cities suffered tremendous health problems
      –cholera, diphtheria and worse – due to the pollution of local water
      sources. One solution was to dam remote pristine rivers and pipe water to
      the crowded population centers.
      <br /><br />
      Still other dams were created to provide flood storage. The agricultural
      miracle in California’s Central Valley could only happen when melted snow
      from the Sierra winters was stored for the growing season. Vast reservoirs
      in the Upper Delaware provide for the water needs of New York City. New
      Jersey is dotted with reservoirs behind dams that were built to serve our
      metropolitan centers over a century ago.
      <br /><br />
      Lake Hopatcong and Lake Musconetcong were built to provide power to
      operate the Morris Canal, an engineering marvel operated from the 1830’s
      until the 1920’s. Fortunes were created from the mountains of coal, iron
      and finished goods transported along the canal from Phillipsburg to Newark
      and Jersey City. The lake waters spun turbines that provided power to lift
      heavy barges up inclined planes between the canal sections.
      <br /><br />
      A great percentage of the most recently built dams, however, serve
      recreational purposes. Waterfront property always carries a premium. In
      New Jersey, the two large lakes of the Morris Canal, Lake Hopatcong and
      Lake Musconetcong, now serve as waterfront amenities to attractive
      lakeside communities.
      <br /><br />
      In the western parts of the US and Canada, dams provide a significant
      amount of the electrical power that is generated. Huge hydroelectric dams
      are considered to be ‘green’ since they do not create carbon dioxide or
      other airborne pollutants that contribute to changing world-wide climate
      patterns. However, as with all dams, there is a negative impact on the
      entire ecosystem when a dam interrupts the natural flow of a river.
    </div>
