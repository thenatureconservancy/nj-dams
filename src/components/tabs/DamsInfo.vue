  <div id="what" class="q-my-md">
    <div class="text-bold">What is a Dam?</div>
    <div>
      There are a number of technical and legal definitions of a dam, but
      generally it is any structure that impounds or diverts water. In New
      Jersey, a dam is defined as any artificial dike, levee or other barrier,
      together with appurtenant works, which is constructed for the purpose of
      impounding water on a permanent or temporary basis, that raises the water
      level five feet or more above the usual, mean, low water height when
      measured from the downstream toe-of-dam to the emergency spillway crest
      or, in the absence of an emergency spillway, the top-of-dam.
    </div>
