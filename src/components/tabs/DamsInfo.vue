  <div id="vocabulary" class="q-my-md">
    <div class="text-bold">Vocabulary</div>
    <div>
      ABUTMENT: The part of the valley side against which the dam is
      constructed. May also refer to an artificial abutment sometimes
      constructed as a concrete wall. Right and left abutments are those on
      respective sides as an observer looks downstream.
      <br /><br />
      BASE WIDTH: The width of the dam measured along the dam/foundation
      interface.
      <br /><br />
      BREACH: An opening or a breakthrough of a dam sometimes caused by rapid
      erosion of a section of earth embankment by water.
      <br /><br />
      CONDUIT: A closed channel to convey the discharge through or under a dam.
      Usually pipes constructed of concrete or steel.
      <br /><br />
      CORE (IMPERVIOUS CORE) (IMPERVIOUS ZONE): A zone of material of low
      permeability in an embankment dam, hence the terms central core, inclined
      core, puddle clay core, and rolled clay core.
      <br /><br />
      CREST LENGTH: The developed length of the top of the dam. This includes
      the length of the spillway, powerhouse, navigation lock, fish pass, etc.,
      where these structures form part of the length of the dam. If detached
      from the dam, these structures should not be included.
      <br /><br />
      CREST OF DAM: The term crest of dam is often used when top of spillway and
      top of dam should be used for referring to the overflow section and dam
      proper, respectively.
      <br /><br />
      CUTOFF: An impervious construction by means of which seepage is reduced or
      prevented from passing through foundation material.
      <br /><br />
      CUTOFF WALL: A wall of impervious material, e.g., concrete, wood pilings,
      steel sheet piling, built into the foundation to reduce seepage under the
      dam.
      <br /><br />
      DRAINAGE LAYER OR BLANKET: A layer of pervious material placed directly
      over the foundation material or downstream slope to facilitate seepage
      drainage of the embankment. May also use an upstream blanket placed on the
      impoundment floor and upstream embankment to prevent seepage entering the
      dam.
      <br /><br />
      DRAWDOWN: The resultant lowering of water surface level due to release of
      water from the reservoir.
      <br /><br />
      EMBANKMENT: Fill material, usually earth or rock, placed with sloping
      sides.
      <br /><br />
      EMERGENCY ACTION PLAN: A predetermined plan of action to be taken to
      reduce the potential for property damage and loss of lives in an area
      affected by a dam break.
      <br /><br />
      FACE: With reference to a structure, the external surface that limits the
      structure, e.g., the face of the wall or dam.
      <br /><br />
      FLASHBOARDS: Lengths of timber, concrete, or steel placed on the crest of
      a spillway to raise the operating water level but that may be quickly
      removed in the event of a flood either by tripping a supporting device or
      by designing the flashboard supports to fail under specified conditions.
      <br /><br />
      FOUNDATION OF DAM: The natural material on which the dam structure is
      placed.
      <br /><br />
      FREEBOARD: The vertical distance from the water surface to the lowest
      elevation at which water would flow over the dam at a section not designed
      to be overflowed.
      <br /><br />
      GATE: In general, a device in which a leaf or member is moved across the
      waterway from an external position to control or stop the flow.
      <br /><br />
      CREST GATE (SPILLWAY GATE): A gate on the crest of a spillway that
      controls overflow or reservoir water level.
      <br /><br />
      FLAP GATE: A gate hinged along one edge, usually either the top or bottom
      edge. Examples of bottom-hinged flap gates are tilting gates and fish
      belly gates so called from their shape in cross section.
      <br /><br />
      OUTLET GATE: A gate controlling the outflow of water from a reservoir.
      <br /><br />
      RADIAL GATE (TAINTER GATE): A gate with a curved upstream plate and radial
      arms hinged to piers or other supporting structures.
      <br /><br />
      SLIDE GATE (SLUICE GATE): A gate that can be opened or closed by sliding
      in supporting guides.
      <br /><br />
      HEEL OF DAM: The junction of the upstream face of a gravity or arch dam
      with the foundation surface. In the case of an embankment dam the junction
      is referred to as the upstream toe of the dam.
      <br /><br />
      INTAKE: Any structure in a reservoir, dam, or river through which water
      can be drawn into an outlet pipe, flume, etc.
      <br /><br />
      LOW LEVEL OUTLET (BOTTOM OUTLET): An opening at a low level from the
      reservoir generally used for emptying the impoundment.
      <br /><br />
      OUTLET: An opening through which water can be freely discharged for a
      particular purpose from a reservoir.
      <br /><br />
      PERVIOUS ZONE: A part of the cross section of an embankment dam comprising
      material of high permeability.
      <br /><br />
      RIPRAP: A layer of large uncoursed stones, broken rock, or precast blocks
      placed in random fashion on the upstream slope of an embankment dam, on a
      reservoir shore, or on the sides of a channel as a protection against wave
      and ice action.
      <br /><br />
      SEEPAGE COLLAR: A projecting collar usually of concrete or steel built
      around the outside of a pipe, tunnel, or conduit, under an embankment dam,
      to lengthen the seepage path along the outer surface of the conduit.
      <br /><br />
      SPILLWAY: A structure over or through which flood flows are discharged. If
      the flow is controlled by gates, it is considered a controlled spillway;
      if the elevation of the spillway crest is the only control, it is
      considered an uncontrolled spillway.
      <br /><br />
      AUXILIARY SPILLWAY (EMERGENCY SPILLWAY): A secondary spillway designed to
      operate only during exceptionally large floods.
      <br /><br />
      OGEE SPILLWAY (OGEE SECTION): An overflow spillway, which in cross section
      the crest, downstream slope, and bucket have an “S” or ogee form of curve.
      The shape is intended to match the underside of the nappe at its upper
      extremities.
      <br /><br />
      SPILLWAY CHANNEL (SPILLWAY TUNNEL): A channel or tunnel conveying water
      from the spillway to the river downstream.
      <br /><br />
      STOPLOGS: Large logs, timbers or steel beams placed on top of each other
      with their ends held in guides on each side of a channel or conduit so as
      to provide a cheaper or more easily handled means of temporary closure
      than a bulkhead gate.
      <br /><br />
      STRUCTURAL HEIGHT: The vertical distance from the lowest point of natural
      ground on the downstream side of the dam to the highest part of the dam
      which would impound water.
      <br /><br />
      TOE OF DAM: The junction of the downstream face of a dam with the natural
      ground surface. This is also referred to as the downstream toe. For an
      embankment dam the junction of the upstream face with ground surface is
      called the upstream toe.
      <br /><br />
      TOP OF DAM: The elevation of the upper most surface of a dam, usually a
      road or walkway, excluding any parapet wall, railings, etc.
      <br /><br />
      TOP THICKNESS (TOP WIDTH): The thickness or width of a dam at the top of
      the dam. In general, the term thickness is used for gravity and arch dams,
      width is used for other dams.
      <br /><br />
      TRAINING WALL: A wall built to confine or guide the flow of water.
      <br /><br />
      TRASH RACK: A screen comprising metal or reinforced concrete bars located
      in the waterway at an intake so as to prevent the ingress of floating or
      submerged debris.
      <br /><br />
      Source: Basic Terms of Dam Characteristics
