  <div id="restoration" class="q-my-md">
    <div class="text-bold">Restoration</div>
    <div>
      Although most rivers cannot be completely restored to historic conditions
      – simply because of the amount of development that has occurred on and
      along them – dam removal can often recreate conditions that move the river
      towards those historic conditions. For example, dam removals have allowed
      the return of migratory fish to the Musconetcong, Millstone and Paulins
      Kill just months after dam removal on those rivers after an absence of a
      century or more.
      <br /><br />
      Dam removal projects typically include restoration that extends beyond
      restoring flows for fish and wildlife. Engineers, biologists, and
      watershed scientists will ensure that a stable river channel exists and
      that it provides plenty of the right type of habitat for local species.
      The surrounding floodplains can be restored to provide good habitat,
      promote good water quality and where possible increase recharge of
      groundwater. If a dam provided flood control, engineers and other
      restoration experts can explore if flood control can be accomplished more
      effectively and for less money by restoring wetlands or by planting or
      maintaining riparian buffers. Often a wide range of stakeholders from the
      public and private sectors weigh in on restoration design.
      <br /><br />
      Generally, the best way to predict how a restored river will look after a
      dam removal is to look at the river upstream of the impoundment and
      downstream of the dam. Unless there is a significant geologic feature in
      the impounded stretch of the river, it is unlikely that the restored river
      will be significantly different than what is seen in free-flowing parts of
      the river. The water surface level after a dam removal can be predicted
      through modeling and/or sounding surveys.
    </div>
