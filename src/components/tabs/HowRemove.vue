  <div class="text-center text-h5 q-mb-md">How to Remove a Dam</div>
  <div>
    In the vast majority of cases, dam removals only proceed with the consent of
    the dam owner. The owner, or the owner and partners, must begin the dam
    removal process by learning as much about the dam as possible, including
    information about its history, hazard classification, safety record, current
    and past uses, construction type, and ownership. Consult the NJDEP Bureau of
    Dam Safety and Flood Control, local historical societies and watershed
    groups, and state and municipal records to help gather this information.
    <br /><br />
    The length of time from initiation of a project through removal varies
    greatly and may last from one year to several years. The timeline depends
    upon the complexity of the pre‐removal activities, including the feasibility
    study and design, the length of time to acquire permits, the timing of
    allowable construction activities, and fundraising. The actual dam removal
    can take anywhere from a few days to a few months.
    <br /><br />
    In addition to addressing the technical issues, there are several community
    or social issues that must be addressed before removing a dam. The most
    common issues are personal or community attachment to the dam and lake or
    impoundment, potential water supply issues (i.e., groundwater wells),
    impacts to property values and historic concerns, among others. Working
    closely with those who assign high value to the impoundment is critical– the
    potential benefits associated with the removal of the dam and the loss of
    the impoundment, and the costs of alternatives (e.g., maintenance, flooding,
    liability), need to be made clear, all while respecting the interests of the
    people.
